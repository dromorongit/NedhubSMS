import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const PORT = 8132;
const server = http.createServer((req,res)=>{ let u=decodeURIComponent(req.url.split('?')[0]); if(u==='/')u='/index.html'; const fp=path.join(ROOT,u); fs.readFile(fp,(e,d)=>{ if(e){res.statusCode=404;res.end('nf');return;} const ext=path.extname(fp).toLowerCase(); res.setHeader('Content-Type',{'.html':'text/html; charset=utf-8','.css':'text/css','.js':'application/javascript'}[ext]||'application/octet-stream'); res.end(d);});});
await new Promise(r=>server.listen(PORT,r));
const browser=await chromium.launch();
const ctx=await browser.newContext();
await ctx.addInitScript(()=>{try{localStorage.setItem('authToken','fake-token-for-screenshot');localStorage.setItem('authStorageType','local');localStorage.setItem('userName','John Doe');}catch(e){}});
const page=await ctx.newPage();
await page.setViewportSize({width:390,height:844});
await page.route('**/api/**', r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify({data:{user:{name:'John Doe',email:'john@example.com',role:'user'},balance:2,senderIds:[{senderId:'NEDHUB',status:'approved'}],contacts:[],blacklistedNumbers:[],blacklisted:[],pagination:{totalPages:1,page:1,total:0,limit:50},transactions:[],campaigns:[],reports:[],messages:[],history:[],recipients:[],total:0,valid:0,invalid:0,duplicates:0,cost:0.04,segments:1,encoding:'gsm7',recipientCount:0,success:true,messageId:'msg_1'},message:'ok'})}));
await page.goto(`http://localhost:${PORT}/src/pages/dashboard/templates.html`,{waitUntil:'networkidle'});
await page.waitForTimeout(1500);
await page.click('.nhs-burger',{force:true});
await page.waitForTimeout(400);
const elAtPoint = await page.evaluate(()=>{const el=document.elementFromPoint(380,100); return el?el.outerHTML.slice(0,120):null;});
console.log('elementFromPoint(380,100):',elAtPoint);
const sidebarRect = await page.evaluate(()=>{const r=document.querySelector('.nhs-sidebar').getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom};});
console.log('sidebarRect',sidebarRect);
// force close via dispatching click on overlay using dispatchEvent
await page.evaluate(()=>{const ov=document.querySelector('.nhs-overlay'); ov.dispatchEvent(new MouseEvent('click',{bubbles:true,cancelable:true,clientX:380,clientY:100}));});
await page.waitForTimeout(400);
const st=await page.evaluate(()=>{const r=document.querySelector('.nhs-sidebar').getBoundingClientRect();return {left:r.left,right:r.right};});
console.log('after dispatch',JSON.stringify(st));
await browser.close();server.close();
